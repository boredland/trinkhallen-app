/**
 * One-shot: emit crates/core/src/i18n/catalog.rs from src/lib/messages.ts so
 * the Rust port carries the exact strings. Run with `bun scripts/gen-i18n-rs.ts`.
 */
import { writeFileSync } from "node:fs";
import {
  MESSAGES,
  OH_LABELS,
  PAYMENT_LABELS,
  REPORT_KIND_LABELS,
  REPORT_STATUS_LABELS,
  STATUS_PILL_LABELS,
  TAG_GROUP_LABELS,
  TAG_LABELS,
  TEMPLATES,
} from "../src/lib/messages";

const lit = (s: string) => JSON.stringify(s);

function table(name: string, m: Record<"de" | "en", Record<string, string>>): string {
  const arm = (lang: "de" | "en") =>
    Object.entries(m[lang])
      .map(([k, v]) => `        (${lit(k)}, ${lit(v)}),`)
      .join("\n");
  return `pub static ${name}_DE: &[(&str, &str)] = &[\n${arm("de")}\n];\npub static ${name}_EN: &[(&str, &str)] = &[\n${arm("en")}\n];\n`;
}

const oh = (lang: "de" | "en") => {
  const o = OH_LABELS[lang];
  return `OhLabels { unknown: ${lit(o.unknown)}, open: ${lit(o.open)}, closed: ${lit(o.closed)}, closed_lower: ${lit(o.closedLower)}, days: [${o.days.map(lit).join(", ")}] }`;
};

const out = `// @generated by scripts/gen-i18n-rs.ts from src/lib/messages.ts — do not edit by hand.
#![allow(clippy::all)]

use super::OhLabels;

${table("MESSAGES", MESSAGES as never)}
${table("TEMPLATES", TEMPLATES as never)}
${table("REPORT_KIND", REPORT_KIND_LABELS as never)}
${table("REPORT_STATUS", REPORT_STATUS_LABELS as never)}
${table("STATUS_PILL", STATUS_PILL_LABELS as never)}
${table("TAG", TAG_LABELS as never)}
${table("PAYMENT", PAYMENT_LABELS as never)}
${table("TAG_GROUP", TAG_GROUP_LABELS as never)}
pub static OH_DE: OhLabels = ${oh("de")};
pub static OH_EN: OhLabels = ${oh("en")};
`;

writeFileSync("crates/core/src/i18n/catalog.rs", out);
console.log(
  `wrote ${Object.keys(MESSAGES.de).length} DE messages, ${Object.keys(MESSAGES.en).length} EN`,
);
