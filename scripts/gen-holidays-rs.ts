/**
 * Emits crates/core/src/hours/holidays_de.rs: German public holidays per
 * Bundesland for 2024–2035, as evaluated by opening_hours.js (the holiday
 * source the TS app used). The Rust `opening-hours` crate only ships a
 * country-wide regional pool, which would mark e.g. Fronleichnam as a holiday
 * in Berlin.
 */
import { writeFileSync } from "node:fs";
import OpeningHours from "opening_hours";

const STATES = [
  ["baden-wuerttemberg", "Baden-Württemberg", 48.78, 9.18],
  ["bayern", "Bayern", 48.14, 11.58],
  ["berlin", "Berlin", 52.52, 13.4],
  ["brandenburg", "Brandenburg", 52.4, 13.06],
  ["bremen", "Bremen", 53.08, 8.8],
  ["hamburg", "Hamburg", 53.55, 9.99],
  ["hessen", "Hessen", 50.11, 8.68],
  ["mecklenburg-vorpommern", "Mecklenburg-Vorpommern", 54.09, 12.13],
  ["niedersachsen", "Niedersachsen", 52.37, 9.73],
  ["nordrhein-westfalen", "Nordrhein-Westfalen", 51.23, 6.78],
  ["rheinland-pfalz", "Rheinland-Pfalz", 50.0, 8.27],
  ["saarland", "Saarland", 49.24, 6.99],
  ["sachsen", "Sachsen", 51.05, 13.74],
  ["sachsen-anhalt", "Sachsen-Anhalt", 52.13, 11.63],
  ["schleswig-holstein", "Schleswig-Holstein", 54.32, 10.13],
  ["thueringen", "Thüringen", 50.98, 11.03],
] as const;

const FROM = new Date("2024-01-01T00:00:00Z");
const TO = new Date("2036-01-01T00:00:00Z");

const blocks: string[] = [];
for (const [, state, lat, lon] of STATES) {
  const oh = new OpeningHours("PH", {
    lat,
    lon,
    address: { country_code: "de", state },
  } as never);
  const days = new Set<string>();
  for (const [start] of oh.getOpenIntervals(FROM, TO) as unknown as Array<[Date, Date]>) {
    days.add(start.toISOString().slice(0, 10));
  }
  const list = [...days]
    .sort()
    .map((d) => `"${d}"`)
    .join(", ");
  blocks.push(`    (${JSON.stringify(state)}, &[${list}]),`);
}

writeFileSync(
  "crates/core/src/hours/holidays_de.rs",
  `// @generated by scripts/gen-holidays-rs.ts from opening_hours.js — do not edit by hand.\n\n/// (Bundesland, public holidays as YYYY-MM-DD), 2024–2035.\npub static HOLIDAYS_DE: &[(&str, &[&str])] = &[\n${blocks.join("\n")}\n];\n`,
);
console.log("ok");
