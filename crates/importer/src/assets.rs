//! `assets` step: move the client bundle into a content-addressed directory
//! and emit the Rust manifest the worker embeds.
//!
//! The bundle is one unit: the wasm-bindgen glue imports `./client_bg.wasm`
//! and `./snippets/…`, the snippets lazily import `../../map.js` and
//! `../../pwa.js`, and `app.css` points at `./fonts/…`. Renaming single files
//! would break those relative URLs, and the snippet directory names are
//! derived from crate identity rather than content - so the whole directory is
//! hashed instead: `/assets/<hash>/client.js`. Every URL under `/assets/` is
//! then content-addressed, which `public/_headers` relies on (`immutable`).

use std::fs;
use std::path::{Path, PathBuf};

use sha2::{Digest, Sha256};

const HASH_LEN: usize = 8;

/// Public URL paths of the entry assets, e.g. `/assets/1a2b3c4d/app.css`.
#[derive(Debug, Default, PartialEq)]
pub struct Manifest {
    pub css: Vec<String>,
    pub client_js: String,
    pub client_wasm: String,
    pub map_js: String,
}

fn is_hash(name: &str) -> bool {
    name.len() == HASH_LEN
        && name
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

/// Every file below `dir`, as sorted `/`-separated relative paths.
fn files(dir: &Path) -> Result<Vec<String>, String> {
    fn walk(root: &Path, dir: &Path, out: &mut Vec<String>) -> Result<(), String> {
        for entry in fs::read_dir(dir).map_err(|e| format!("read {}: {e}", dir.display()))? {
            let path = entry.map_err(|e| e.to_string())?.path();
            if path.is_dir() {
                walk(root, &path, out)?;
            } else {
                let rel = path.strip_prefix(root).map_err(|e| e.to_string())?;
                let parts: Vec<_> = rel
                    .components()
                    .map(|c| c.as_os_str().to_string_lossy().into_owned())
                    .collect();
                out.push(parts.join("/"));
            }
        }
        Ok(())
    }
    let mut out = Vec::new();
    walk(dir, dir, &mut out)?;
    out.sort();
    Ok(out)
}

/// First 8 hex chars of a SHA-256 over every file's relative path and bytes.
pub fn bundle_hash(dir: &Path) -> Result<String, String> {
    let mut h = Sha256::new();
    for rel in files(dir)? {
        let bytes = fs::read(dir.join(&rel)).map_err(|e| format!("read {rel}: {e}"))?;
        h.update((rel.len() as u64).to_le_bytes());
        h.update(rel.as_bytes());
        h.update((bytes.len() as u64).to_le_bytes());
        h.update(&bytes);
    }
    Ok(h.finalize()
        .iter()
        .take(HASH_LEN / 2)
        .map(|b| format!("{b:02x}"))
        .collect())
}

/// Move everything in `dir` into `dir/<hash>/`; returns the hash. A directory
/// holding exactly one hashed bundle is left as is.
pub fn hash_dir(dir: &Path) -> Result<String, String> {
    let entries: Vec<PathBuf> = fs::read_dir(dir)
        .map_err(|e| format!("read {}: {e}", dir.display()))?
        .map(|e| e.map(|e| e.path()).map_err(|e| e.to_string()))
        .collect::<Result<_, _>>()?;
    let name = |p: &Path| {
        p.file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_default()
    };
    if let [only] = entries.as_slice() {
        if only.is_dir() && is_hash(&name(only)) {
            return Ok(name(only));
        }
    }
    if entries.iter().any(|p| p.is_dir() && is_hash(&name(p))) {
        return Err(format!(
            "{} mixes a hashed bundle with new files; clean it first",
            dir.display()
        ));
    }
    let hash = bundle_hash(dir)?;
    let target = dir.join(&hash);
    fs::create_dir(&target).map_err(|e| format!("create {}: {e}", target.display()))?;
    for p in entries {
        fs::rename(&p, target.join(name(&p))).map_err(|e| format!("move {}: {e}", p.display()))?;
    }
    Ok(hash)
}

/// Entry asset URLs inside the bundle. A missing entry is an error: shipping
/// an empty URL would render a page that loads nothing.
pub fn resolve(dir: &Path, hash: &str) -> Result<Manifest, String> {
    let bundle = dir.join(hash);
    let url = |file: &str| -> Result<String, String> {
        if bundle.join(file).is_file() {
            Ok(format!("/assets/{hash}/{file}"))
        } else {
            Err(format!("no `{file}` in the client bundle"))
        }
    };
    Ok(Manifest {
        css: vec![url("app.css")?],
        client_js: url("client.js")?,
        client_wasm: url("client_bg.wasm")?,
        map_js: url("map.js")?,
    })
}

/// Source of `crates/worker/src/assets_manifest.rs`.
pub fn render(m: &Manifest) -> String {
    let css: Vec<String> = m.css.iter().map(|c| format!("{c:?}")).collect();
    format!(
        "// @generated by trinkhallen-importer (assets) — do not edit by hand.\n\
         \n\
         pub const CSS: &[&str] = &[{}];\n\
         pub const CLIENT_JS: &str = {:?};\n\
         pub const CLIENT_WASM: &str = {:?};\n\
         pub const MAP_JS: &str = {:?};\n",
        css.join(", "),
        m.client_js,
        m.client_wasm,
        m.map_js
    )
}

pub fn run(dir: &Path, manifest_rs: &Path) -> Result<Manifest, String> {
    let hash = hash_dir(dir)?;
    let manifest = resolve(dir, &hash)?;
    // Same content → leave the file alone; `wrangler dev` watches the tree and
    // would otherwise rebuild in a loop.
    let src = render(&manifest);
    if fs::read_to_string(manifest_rs).ok().as_deref() != Some(src.as_str()) {
        fs::write(manifest_rs, src).map_err(|e| format!("write {}: {e}", manifest_rs.display()))?;
    }
    println!(
        "  bundle /assets/{hash}/; manifest → {}",
        manifest_rs.display()
    );
    Ok(manifest)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn touch(dir: &Path, rel: &str, body: &str) {
        let p = dir.join(rel);
        fs::create_dir_all(p.parent().unwrap()).unwrap();
        fs::write(p, body).unwrap();
    }

    fn bundle(dir: &Path, wasm: &str) {
        for (rel, body) in [
            ("app.css", "a"),
            ("client.js", "b"),
            ("map.js", "d"),
            ("snippets/x/inline0.js", "s"),
            ("fonts/inter.woff2", "f"),
        ] {
            touch(dir, rel, body);
        }
        touch(dir, "client_bg.wasm", wasm);
    }

    #[test]
    fn any_file_change_moves_the_bundle_to_a_new_url() {
        let (a, b) = (tempfile::tempdir().unwrap(), tempfile::tempdir().unwrap());
        bundle(a.path(), "c");
        bundle(b.path(), "c");
        assert_eq!(
            bundle_hash(a.path()).unwrap(),
            bundle_hash(b.path()).unwrap()
        );
        // A snippet edit alone must change every URL, or immutable caches
        // would pair old snippets with a new wasm.
        touch(b.path(), "snippets/x/inline0.js", "s2");
        assert_ne!(
            bundle_hash(a.path()).unwrap(),
            bundle_hash(b.path()).unwrap()
        );
    }

    #[test]
    fn keeps_relative_layout_and_is_idempotent() {
        let dir = tempfile::tempdir().unwrap();
        bundle(dir.path(), "c");
        let hash = hash_dir(dir.path()).unwrap();
        assert_eq!(hash_dir(dir.path()).unwrap(), hash);
        let root = dir.path().join(&hash);
        for rel in [
            "client.js",
            "client_bg.wasm",
            "snippets/x/inline0.js",
            "fonts/inter.woff2",
        ] {
            assert!(root.join(rel).is_file(), "{rel}");
        }
        touch(dir.path(), "late.js", "x");
        assert!(
            hash_dir(dir.path()).is_err(),
            "a second build must not mix into the bundle"
        );
    }

    #[test]
    fn emits_the_worker_manifest() {
        let dir = tempfile::tempdir().unwrap();
        bundle(dir.path(), "c");
        let out = dir.path().join("m.rs");
        let m = run(dir.path(), &out).unwrap();
        let src = fs::read_to_string(&out).unwrap();
        assert!(src.starts_with("// @generated"));
        let h = m.client_js.split('/').nth(2).unwrap();
        assert!(is_hash(h), "{h}");
        assert!(src.contains(&format!(
            "pub const CSS: &[&str] = &[\"/assets/{h}/app.css\"];"
        )));
        assert!(src.contains(&format!(
            "pub const CLIENT_JS: &str = \"/assets/{h}/client.js\";"
        )));
        assert!(src.contains(&format!(
            "pub const CLIENT_WASM: &str = \"/assets/{h}/client_bg.wasm\";"
        )));
        assert!(src.contains(&format!("pub const MAP_JS: &str = \"/assets/{h}/map.js\";")));
    }

    #[test]
    fn missing_entry_is_an_error() {
        let dir = tempfile::tempdir().unwrap();
        touch(dir.path(), "app.css", "a");
        let err = run(dir.path(), &dir.path().join("m.rs")).unwrap_err();
        assert!(err.contains("client.js"), "{err}");
    }
}
