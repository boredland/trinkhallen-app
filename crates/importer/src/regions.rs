//! `regions.yml` parsing and the generated `trinkhallen_core::regions` table.

use serde::Deserialize;

#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct Region {
    pub slug: String,
    pub path: String,
    pub prefix: String,
    pub bbox: [f64; 4],
    /// Absent = city; `rest` marks a catch-all bucket for a Bundesland/country.
    #[serde(default)]
    pub role: Option<String>,
}

#[derive(Deserialize)]
struct Doc {
    regions: Vec<Region>,
}

pub fn parse(yaml: &str) -> Result<Vec<Region>, String> {
    let doc: Doc = serde_yaml_ng::from_str(yaml).map_err(|e| format!("regions.yml: {e}"))?;
    validate(&doc.regions)?;
    Ok(doc.regions)
}

/// Prefixes are embedded in minted ids (`tk_<prefix>_<rest>`) and parsed back
/// by `parse_prefix`, which only accepts `[a-z0-9]+`; anything else would mint
/// ids that no region owns.
fn validate(regions: &[Region]) -> Result<(), String> {
    for r in regions {
        if r.prefix.is_empty()
            || !r
                .prefix
                .bytes()
                .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit())
        {
            return Err(format!(
                "region {}: prefix {:?} is not [a-z0-9]+",
                r.slug, r.prefix
            ));
        }
        match r.role.as_deref() {
            None | Some("city") | Some("rest") => {}
            Some(other) => return Err(format!("region {}: unknown role {other:?}", r.slug)),
        }
    }
    Ok(())
}

/// Source of `crates/core/src/regions/generated.rs`. Lists every region in the
/// YAML, including ones whose data file is missing: the table describes the
/// repo, not this bundle.
pub fn render_generated(regions: &[Region]) -> String {
    let mut out = String::from(
        "// @generated by trinkhallen-importer from trinkhallen-data/regions.yml — do not edit by hand.\n\n\
         use super::{Region, Role};\n\n\
         pub static REGIONS: &[Region] = &[\n",
    );
    for r in regions {
        let role = if r.role.as_deref() == Some("rest") {
            "Rest"
        } else {
            "City"
        };
        let [w, s, e, n] = r.bbox;
        out.push_str(&format!(
            "    Region {{ slug: {:?}, path: {:?}, prefix: {:?}, bbox: [{w:?}, {s:?}, {e:?}, {n:?}], role: Role::{role} }},\n",
            r.slug, r.path, r.prefix
        ));
    }
    out.push_str("];\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    const YAML: &str = r#"
regions:
  - slug: frankfurt
    path: data/de/hessen/frankfurt.geojson
    prefix: fr
    iso3166_2: DE-HE
    admin_level: 6
    bbox: [7.90, 49.84, 9.48, 50.61]
  - slug: hessen-rest
    path: data/de/hessen/_rest.geojson
    prefix: her
    iso3166_2: DE-HE
    admin_level: 4
    role: rest
    bbox_clip: [1, 2, 3, 4]
    bbox: [7.77, 49.39, 10.24, 51.66]
  - slug: magdeburg
    path: data/de/sachsen-anhalt/magdeburg.geojson
    prefix: md
    bbox: [11.5, 52, 11.8, 52.25]
"#;

    #[test]
    fn parses_and_renders_the_generated_table() {
        let regions = parse(YAML).unwrap();
        assert_eq!(regions.len(), 3);
        assert_eq!(
            render_generated(&regions),
            "// @generated by trinkhallen-importer from trinkhallen-data/regions.yml — do not edit by hand.\n\n\
             use super::{Region, Role};\n\n\
             pub static REGIONS: &[Region] = &[\n\
             \x20   Region { slug: \"frankfurt\", path: \"data/de/hessen/frankfurt.geojson\", prefix: \"fr\", bbox: [7.9, 49.84, 9.48, 50.61], role: Role::City },\n\
             \x20   Region { slug: \"hessen-rest\", path: \"data/de/hessen/_rest.geojson\", prefix: \"her\", bbox: [7.77, 49.39, 10.24, 51.66], role: Role::Rest },\n\
             \x20   Region { slug: \"magdeburg\", path: \"data/de/sachsen-anhalt/magdeburg.geojson\", prefix: \"md\", bbox: [11.5, 52.0, 11.8, 52.25], role: Role::City },\n\
             ];\n"
        );
    }

    #[test]
    fn rejects_prefixes_outside_lowercase_alphanumerics() {
        for bad in ["Fr", "f_r", "f-r", "", "fü"] {
            let yaml = format!(
                "regions:\n  - slug: x\n    path: p\n    prefix: \"{bad}\"\n    bbox: [1, 2, 3, 4]\n"
            );
            assert!(
                parse(&yaml).unwrap_err().contains("not [a-z0-9]+"),
                "prefix {bad:?} accepted"
            );
        }
    }

    #[test]
    fn rejects_unknown_roles() {
        let yaml = "regions:\n  - slug: x\n    path: p\n    prefix: x\n    role: weird\n    bbox: [1, 2, 3, 4]\n";
        assert!(parse(yaml).unwrap_err().contains("unknown role"));
    }
}
